// ============================================================================
// Per-city meta: currency, airports, transit card, seasonality, events, phrases.
//
// Airport codes, currencies, time zones, transit-card names and the phrases are
// factual. `seasons` ratings are EDITORIAL ESTIMATES (1–5) drawn from published
// climate normals and tourism-board seasonality; they are labelled as estimates
// wherever they are shown in the UI.
// ============================================================================

type Rating = 1 | 2 | 3 | 4 | 5;

/** Builds the 12 monthly ratings (January first) from three 12-value rows. */
function seasons(crowds: Rating[], weather: Rating[], price: Rating[]): SeasonRating[] {
  return crowds.map((c, i) => ({ crowds: c, weather: weather[i], price: price[i] }));
}

