/**
 * One-off: parse the free-text `approxCost` strings ("€15", "€35–55",
 * "THB 60–200") into numeric costMin / costMax / costCurrency and store them in
 * the generated overlay (lib/data/generated/<slug>.json). The original text is
 * left untouched in the source files as `approxCost`.
 *
 * Anything ambiguous (several amounts, optional extras, open-ended "+", no
 * number at all) is still parsed on a best-effort basis where that is safe and
 * is listed in docs/cost-parse-report.md for manual review.
 *
 * Run: npx tsx scripts/parse-costs.ts
 */
import fs from "node:fs";
import path from "node:path";
import { destinations } from "../lib/data";
import { parseCost, type ParsedCost } from "../lib/cost-text";
import { patchPlace, readOverlay, writeOverlay } from "./lib/overlay";

type Parsed = ParsedCost;

/**
 * Manual decisions for strings the generic parser cannot read correctly.
 * Keyed `<slug>:<id>`; each entry replaces the parsed fields.
 */
const OVERRIDES: Record<string, Parsed> = {
  // Palace and Secret Garden are separate tickets; both together is the realistic high end.
  "seoul:changdeokgung": { min: 3000, max: 8000, currency: "KRW", note: "palace ₩3,000 + Secret Garden ₩5,000 sold separately; max is both" },
  // Free beaches up to a paid attraction.
  "singapore:x-sentosa-island-day": { min: 0, max: 80, currency: "SGD", note: "free beaches up to ~S$80 for Universal Studios (stated as 80+)" },
  // Free gardens; the two paid attractions add up if both are done.
  "singapore:gardens-by-the-bay": { min: 0, max: 46, currency: "SGD", note: "domes S$32 + Supertree walkway S$14; max is both" },
  "singapore:singapore-zoo": { min: 48, max: 55, currency: "SGD", note: "zoo S$48 or Night Safari S$55 (separate tickets)" },
};

function main() {
  const rows: string[] = [];
  let parsed = 0;
  for (const dest of destinations) {
    const overlay = readOverlay(dest.slug);
    const seen = new Set<string>();
    const items: { id: string; name: string; approxCost?: string }[] = [
      ...dest.landmarks,
      ...dest.restaurants,
      ...dest.experiences,
      ...dest.dayTrips,
      ...dest.nightlife,
      ...dest.shopping,
    ];
    for (const item of items) {
      if (!item.approxCost) continue;
      const p: Parsed = { ...parseCost(item.approxCost, dest.currency), ...(OVERRIDES[`${dest.slug}:${item.id}`] ?? {}) };
      if (seen.has(item.id)) continue;
      seen.add(item.id);
      if (p.min !== undefined) {
        const patch: Record<string, unknown> = { costMin: p.min, costCurrency: p.currency };
        if (p.max !== undefined) patch.costMax = p.max;
        patchPlace(overlay, item.id, patch);
        parsed++;
      }
      if (p.note) rows.push(`| ${dest.city} | ${item.name} | \`${item.approxCost}\` | ${p.min ?? "–"} | ${p.max ?? "–"} | ${p.currency ?? "–"} | ${p.note} |`);
    }
    writeOverlay(dest.slug, overlay);
  }
  const report = [
    "# Cost parse report",
    "",
    `Generated by \`scripts/parse-costs.ts\`. ${parsed} cost strings were turned into numeric ranges.`,
    "The rows below were ambiguous and deserve a manual look. The original text is always kept as `approxCost`.",
    "",
    "| City | Item | Original text | costMin | costMax | Currency | Why it needs review |",
    "|---|---|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
  fs.mkdirSync(path.join(process.cwd(), "docs"), { recursive: true });
  fs.writeFileSync(path.join(process.cwd(), "docs", "cost-parse-report.md"), report);
  console.log(`parsed ${parsed} costs, ${rows.length} need review (docs/cost-parse-report.md)`);
}

main();
