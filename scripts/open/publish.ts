/** Writes lib/data/open/index.json and the lazy loader map from the per-city JSON files and photo manifest. */
import fs from "node:fs";
import path from "node:path";
import { readPhotos } from "./photos";
import type { Destination } from "../../lib/types";

const OPEN_DIR = path.join(process.cwd(), "lib", "data", "open");

export interface OpenIndexEntry {
  slug: string;
  city: string;
  country: string;
  region: string;
  tagline: string;
  landmarks: number;
  places: number;
  hasPhoto: boolean;
}

export function publishIndex() {
  const photos = readPhotos();
  const files = fs.readdirSync(OPEN_DIR).filter((f) => f.endsWith(".json") && !["index.json", "photos.json"].includes(f)).sort();
  const entries: OpenIndexEntry[] = files.map((f) => {
    const d = JSON.parse(fs.readFileSync(path.join(OPEN_DIR, f), "utf8")) as Destination;
    return {
      slug: d.slug,
      city: d.city,
      country: d.country,
      region: d.region ?? "",
      tagline: d.tagline,
      landmarks: d.landmarks.length,
      places: d.landmarks.length + d.restaurants.length + d.cafes.length + d.nightlife.length + d.shopping.length,
      hasPhoto: !!photos[d.slug],
    };
  });
  fs.writeFileSync(path.join(OPEN_DIR, "index.json"), JSON.stringify(entries, null, 1) + "\n");
  const lines = [
    "// GENERATED by scripts/open/publish.ts. Do not edit.",
    'import type { Destination } from "../../types";',
    "",
    "/** One lazy chunk per open-data city, loaded only when that city is opened. */",
    "export const openLoaders: Record<string, () => Promise<Destination>> = {",
    ...entries.map((e) => `  ${JSON.stringify(e.slug)}: () => import("./${e.slug}.json").then((m) => m.default as unknown as Destination),`),
    "};",
    "",
  ];
  fs.writeFileSync(path.join(OPEN_DIR, "loaders.ts"), lines.join("\n"));
  return entries;
}

if (process.argv[1]?.endsWith("publish.ts")) console.log(`published index: ${publishIndex().length} open cities`);
