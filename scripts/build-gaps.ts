/**
 * Writes data-gaps.md from the merged catalog: every record whose coordinates
 * or official URL could not be confirmed from a primary source
 * (OpenStreetMap / Wikidata), plus coverage statistics.
 *
 * Run after scripts/enrich-geo.ts:  npx tsx scripts/build-gaps.ts
 */
import fs from "node:fs";
import path from "node:path";
import { destinations } from "../lib/data";

type Item = { id: string; name: string; coords?: unknown; officialUrl?: string; openingHours?: unknown; closedDays?: number[]; costMin?: number };

const rows: string[] = [];
const summary: string[] = [];
let totalRecords = 0;
let totalCoords = 0;
let totalUrls = 0;
let totalHours = 0;

for (const d of destinations) {
  const groups: [string, Item[]][] = [
    ["landmark", d.landmarks],
    ["restaurant", d.restaurants],
    ["cafe", d.cafes as Item[]],
    ["shopping", d.shopping],
    ["nightlife", d.nightlife],
    ["experience", d.experiences],
    ["day trip", d.dayTrips],
  ];
  const noCoords: string[] = [];
  const noUrl: string[] = [];
  let n = 0;
  let c = 0;
  let u = 0;
  let h = 0;
  for (const [kind, items] of groups) {
    for (const it of items) {
      n++;
      if (it.coords) c++;
      else noCoords.push(`${it.name} (${kind})`);
      if (it.officialUrl) u++;
      else if (it.coords) noUrl.push(`${it.name} (${kind})`);
      if (it.openingHours || (it.closedDays && it.closedDays.length)) h++;
    }
  }
  const hoodsNo = d.neighborhoods.filter((x) => !x.coords).map((x) => x.name);
  totalRecords += n;
  totalCoords += c;
  totalUrls += u;
  totalHours += h;
  summary.push(`| ${d.city} | ${n} | ${c} | ${u} | ${h} | ${n - c} |`);
  rows.push(`## ${d.city}`, "");
  if (noCoords.length) {
    rows.push(`**Coordinates not confirmed (${noCoords.length}).** No confident OpenStreetMap match inside the city area. Each stays undefined; the planner falls back to its neighborhood centre for distance estimates.`, "");
    rows.push(...noCoords.map((x) => `- ${x}`), "");
  }
  if (noUrl.length) {
    rows.push(`**Official URL not confirmed (${noUrl.length}).** Located on the map, but neither OpenStreetMap nor Wikidata lists the venue's own website.`, "");
    rows.push(...noUrl.map((x) => `- ${x}`), "");
  }
  if (hoodsNo.length) rows.push(`**Neighborhood centre not confirmed:** ${hoodsNo.join(", ")}`, "");
  if (!noCoords.length && !noUrl.length && !hoodsNo.length) rows.push("Nothing outstanding.", "");
}

const out = [
  "# Data gaps",
  "",
  "Generated by `scripts/build-gaps.ts` from the merged catalog. Nothing below was guessed: when a fact could not be",
  "confirmed from a primary source (the venue's own site, official tourism board, Wikipedia/Wikidata, OpenStreetMap) the",
  "field is left undefined.",
  "",
  "How facts get in: `scripts/enrich-geo.ts` queries OpenStreetMap Nominatim (1 request per second, identifying",
  "User-Agent) and Wikidata. A match is only applied when it lies inside the city area **and** its name matches. Opening",
  "hours come from the OSM `opening_hours` tag and are only kept when they can be represented exactly; seasonal or",
  "holiday rules are skipped. Prices are the original hand-written `approxCost` text, parsed by",
  "`scripts/parse-costs.ts` (see `docs/cost-parse-report.md`); new records added in this pass carry no price unless free.",
  "",
  "| City | Records | With coordinates | With official URL | With opening hours or closed day | Without coordinates |",
  "|---|---:|---:|---:|---:|---:|",
  ...summary,
  `| **Total** | **${totalRecords}** | **${totalCoords}** | **${totalUrls}** | **${totalHours}** | **${totalRecords - totalCoords}** |`,
  "",
  "Experiences are mostly activities (a cruise, a cooking class) rather than a single venue, so most of them have no",
  "coordinates by design; the engine places them near the rest of the day instead.",
  "",
  ...rows,
].join("\n");

fs.writeFileSync(path.join(process.cwd(), "data-gaps.md"), out + "\n");
console.log(`data-gaps.md written: ${totalCoords}/${totalRecords} located, ${totalUrls} with official URLs, ${totalHours} with hours`);
